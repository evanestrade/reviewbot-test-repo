/** Small arithmetic helper. */
public final class Calculator {

  /**
   * Adds two integers.
   *
   * @param a first operand
   * @param b second operand
   * @return the sum of a and b
   */
  public int add(int a, int b) {
    return a + b;
  }

  /**
   * Adds two integers.
   *
   * @param a first operand
   * @param b second operand
   * @return the mul of a and b
   */
  public int mult(int a, int b) {
    return a * b;
  }
}
